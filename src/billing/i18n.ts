export type BKey = keyof typeof S;
const I: Record<UiLang, 0 | 1 | 2> = { en: 0, es: 1, fa: 2 };
export const bt = (l: UiLang, k: BKey): string => S[k][I[l]];
export const li = (l: UiLang) => I[l];

export function money(l: UiLang, n: number, ccy: string): string {
  const s = new Intl.NumberFormat(l === 'fa' ? 'fa-IR' : l === 'es' ? 'es-ES' : 'en-US', { minimumFractionDigits: n % 1 ? 2 : 0, maximumFractionDigits: 2 }).format(n);
  return l === 'fa' ? `${s} ${ccy}` : `${ccy} ${s}`;
}
export function day(l: UiLang, ms: number): string {
  return new Date(ms).toLocaleDateString(l === 'fa' ? 'fa-IR' : l === 'es' ? 'es-ES' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
}
